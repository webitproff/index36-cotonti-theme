/**
 * Возвращает локализованный статус legacy-режима Cotonti.
 *
 * Проверяет значение Cot::$cfg['legacyMode'] и возвращает
 * соответствующую языковую строку из языкового файла темы:
 *   - langSkStr_footer_legacy_mode_on  — если режим включён;
 *   - langSkStr_footer_legacy_mode_off — если режим выключен.
 *
 * Строки локализации берутся через фасад Cot::$L, чтобы функция
 * работала корректно даже после переопределения $L в теме.
 *
 * @return string Локализованный текст статуса.
 *
 * @example
 *   В шаблоне footer.tpl:
 *     {PHP|index36_legacy_mode_status()}
 *
 *   В PHP-коде:
 *     $status = index36_legacy_mode_status();
 *     Cot::$out['legacyMode'] = $status;
 */
if (!function_exists('index36_legacy_mode_status')) {
    function index36_legacy_mode_status()
    {
        if (isset(Cot::$cfg['legacyMode']) && Cot::$cfg['legacyMode'] === true) {
            return Cot::$L['langSkStr_footer_legacy_mode_on'];
        }

        return Cot::$L['langSkStr_footer_legacy_mode_off'];
    }
}
