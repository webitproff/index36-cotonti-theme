/* =====================================================================
 * ДОКУМЕНТАЦИЯ ПО ФАЙЛУ index36.functions.php
 * =====================================================================
 *
 * Назначение файла:
 *   Файл index36.functions.php содержит пользовательские функции темы
 *   Index36. Эти функции используются в шаблонах, в файле ресурсов темы
 *   (index36.php), в файле регистрации CSS/JS (index36.rc.php),
 *   а также в модулях и плагинах, подключаемых в контексте активной
 *   темы.
 *
 *   Файл не является ни плагином, ни модулем, ни частью ядра Cotonti.
 *   Он относится к категории вспомогательных файлов темы наряду с:
 *     - index36.php            — точка входа и переопределения $R;
 *     - index36.rc.php         — регистрация CSS/JS ресурсов;
 *     - index36.{lang}.lang.php — языковые строки темы;
 *     - header.tpl, footer.tpl — шаблоны.
 *
 *   Все эти файлы образуют единую сущность — тему оформления сайта.
 *   Каждый файл отвечает за свой аспект: шаблоны — за разметку,
 *   ресурсный файл — за переопределения, файл ресурсов — за CSS/JS,
 *   файл функций — за логику, которую удобнее держать отдельно.
 *
 * =====================================================================
 * МЕСТО В АРХИТЕКТУРЕ COTONTI
 * =====================================================================
 *
 *   Движок Cotonti НЕ подключает index36.functions.php автоматически.
 *   Это не штатный файл ядра, а соглашение, принятое в теме Index36.
 *   Файл подключается вручную из index36.php в самом начале, до
 *   объявления ресурсных строк $R.
 *
 *   Цепочка загрузки в system/common.php (для фронта):
 *
 *     1. Инициализация окружения, подключение к БД, Cot::init().
 *     2. Загрузка конфигурации из базы данных.
 *     3. Определение пользователя и вычисление $usr['theme'].
 *     4. Загрузка языков main, users (admin при COT_ADMIN).
 *     5. Подключение языкового файла темы: {theme}.{lang}.lang.php.
 *     6. Загрузка system/resources.rc.php.
 *     7. Загрузка system/admin/admin.resources.php (при COT_ADMIN).
 *     8. Подключение файла ресурсов темы: index36.php  ← ЭТОТ ФАЙЛ
 *          └── require_once index36.functions.php       ← ПОДКЛЮЧАЕТСЯ
 *     9. Загрузка иконпака.
 *    10. Инициализация XTemplate.
 *    11. Подключение index36.rc.php (секция Head Resources).
 *    12. Выполнение глобального хука 'global'.
 *    13. Рендеринг шаблонов.
 *
 *   Из этой последовательности видно, что index36.functions.php
 *   становится доступен:
 *
 *     - до объявления всех ресурсных строк $R в index36.php;
 *     - до подключения index36.rc.php;
 *     - до инициализации XTemplate;
 *     - до выполнения глобального хука;
 *     - до старта рендеринга шаблонов.
 *
 *   Это означает, что функции темы можно безопасно использовать во всех
 *   перечисленных точках, кроме тех, которые выполняются до шага 8.
 *
 * =====================================================================
 * ЧТО ДОСТУПНО НА МОМЕНТ ВЫПОЛНЕНИЯ
 * =====================================================================
 *
 *   К моменту подключения этого файла в области видимости доступны:
 *
 *   - Cot::$cfg     — полная конфигурация сайта;
 *   - Cot::$usr     — данные текущего пользователя, включая theme;
 *   - Cot::$sys     — системные переменные (abs_url, site_uri, now);
 *   - Cot::$db      — объект базы данных CotDB;
 *   - Cot::$L       — языковые строки (main, users, admin, тема);
 *   - Cot::$env     — переменные окружения расширения;
 *   - $L, $R        — локальные ссылки на массивы языковых и ресурсных
 *                     строк (для совместимости со старым кодом);
 *   - $cfg, $usr, $sys, $db — локальные ссылки на соответствующие
 *                     массивы (для совместимости со старым кодом);
 *   - $structure    — дерево структуры (категорий) сайта;
 *   - $cot_groups   — список групп пользователей;
 *   - $cache        — объект кэша (если включён);
 *   - $theme        — имя текущей темы;
 *   - $scheme       — имя активной цветовой схемы.
 *
 *   К моменту выполнения файла уже загружены функции ядра Cotonti:
 *   cot_url(), cot_rc(), cot_date(), cot_import(), cot_auth(),
 *   cot_incfile(), cot_langfile(), cot_build_*(), cot_page_*() и др.
 *
 * =====================================================================
 * ЧТО НЕ ДОСТУПНО НА МОМЕНТ ВЫПОЛНЕНИЯ
 * =====================================================================
 *
 *   Следующие сущности ещё НЕ готовы к использованию:
 *
 *   - XTemplate не инициализирован (инициализация на шаге 10);
 *   - глобальный хук 'global' ещё не выполнен (шаг 12);
 *   - секция Head Resources не выполнена (шаг 11);
 *   - index36.rc.php ещё не подключён;
 *   - $out ещё не заполнен полностью;
 *   - $env['location'], $env['ext'] могут быть ещё не заданы.
 *
 *   Поэтому в функциях темы нельзя:
 *   - обращаться к $t->assign() до инициализации XTemplate;
 *   - полагаться на хуки, которые выполнятся позже;
 *   - использовать ресурсы, зарегистрированные в .rc.php;
 *   - ожидать полностью заполненный $out.
 *
 * =====================================================================
 * ПРАВИЛА ОФОРМЛЕНИЯ ФУНКЦИЙ
 * =====================================================================
 *
 *  1. Уникальный префикс.
 *     Каждая функция темы должна иметь уникальный префикс, совпадающий
 *     с кодом темы. Для темы Index36 префикс — index36_ или getIndex36.
 *     Это защищает от коллизий с функциями ядра, модулей, плагинов и
 *     других тем.
 *
 *     Плохо:  function get_revision() { ... }
 *     Хорошо: function index36_get_revision() { ... }
 *
 *  2. Защита от повторного объявления.
 *     Каждая функция обёрнута в if (!function_exists('...')). Это
 *     защищает от фатальной ошибки «Cannot redeclare function», если
 *     файл по какой-то причине будет подключён дважды.
 *
 *  3. DocBlock.
 *     Каждая функция снабжена PHPDoc-блоком с описанием, @param,
 *     @return, @global (если используются глобальные переменные),
 *     @see, @example, если уместно.
 *
 *  4. Отсутствие побочных эффектов при подключении.
 *     Файл только объявляет функции. Никаких SQL-запросов,
 *     никаких изменений $cfg, $usr, $sys, $out, никаких выводов
 *     в stdout. Всё выполняется только в момент вызова функции.
 *
 *  5. Идемпотентность.
 *     Повторное подключение файла не должно менять состояние системы.
 *
 *  6. Никакого вывода в stdout/stderr.
 *     Файл выполняется до отправки HTML, поэтому echo, print,
 *     var_dump, print_r с выводом сломают заголовки. Для отладки
 *     использовать error_log().
 *
 *  7. Строгая типизация возвращаемых значений.
 *     По возможности возвращать конкретный тип, использовать
 *     объявления типов параметров и возвращаемого значения.
 *
 *  8. Обработка исключений.
 *     SQL-запросы и файловые операции оборачивать в try/catch
 *     с записью в error_log(), чтобы не обрушить страницу.
 *
 *  9. Минимум зависимостей.
 *     Чем меньше функция зависит от глобального состояния, тем
 *     проще её тестировать и переиспользовать. Передавать параметры
 *     явно, а не читать из глобальных переменных.
 *
 * 10. Единый стиль.
 *     Соблюдать один стиль наименования: snake_case или camelCase.
 *     В Cotonti ядро использует snake_case, поэтому предпочтительно
 *     использовать index36_snake_case.
