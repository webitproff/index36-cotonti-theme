/**
 * Возвращает значение revision из таблицы cot_updates.
 *
 * Значение revision используется для отображения версии базы данных
 * в футере или в админ-панели. Если запись отсутствует или произошла
 * ошибка базы данных, функция возвращает null.
 *
 * Имя функции снабжено префиксом index36_ для предотвращения коллизий
 * с функциями ядра и других расширений.
 *
 * @return string|null Экранированное значение revision или null при ошибке.
 *
 * @example
 *   В шаблоне footer.tpl:
 *     {PHP|index36_get_revision()}
 *
 *   В PHP-коде:
 *     $revision = index36_get_revision();
 *     if ($revision !== null) {
 *         echo 'DB revision: ' . $revision;
 *     }
 */
if (!function_exists('index36_get_revision')) {
    function index36_get_revision()
    {
        try {
            $sql = Cot::$db->query(
                'SELECT upd_value FROM ' . Cot::$db->updates . ' WHERE upd_param = ?',
                'revision'
            );
            $value = $sql->fetchColumn();
        } catch (PDOException $e) {
            error_log('index36_get_revision error: ' . $e->getMessage());
            return null;
        }

        if ($value === false || $value === null) {
            return null;
        }

        return htmlspecialchars((string) $value);
    }
}

