/* =====================================================================
 * ФУНКЦИИ ТЕМЫ INDEX36
 * =====================================================================
 *
 * Назначение:
 *   Пользовательские функции темы Index36. Все функции этого файла
 *   вызываются из шаблонов XTemplate через синтаксис {PHP|func_name()}
 *   или из PHP-кода темы.
 *
 * Ключевое правило: функции, вызываемые из шаблонов, ВСЕГДА возвращают
 * строку и НИКОГДА не бросают исключений. Это требование продиктовано
 * устройством движка CoTemplate (system/cotemplate.php), который:
 *
 *   1. Не оборачивает вызов функции в try/catch. Любое исключение
 *      внутри функции обрушит страницу.
 *
 *   2. Приводит результат к строке через конкатенацию. Возврат null,
 *      false или массива приводит к пустой строке или PHP warning.
 *
 *   3. Не экранирует результат. Если функция возвращает пользовательские
 *      данные — это XSS-уязвимость. Экранирование выполняется внутри
 *      самой функции.
 *
 *   4. Если функция не существует, движок подставляет буквальный текст
 *      тега в HTML. Чтобы этого не происходило, в шаблоне используется
 *      проверка <!-- IF {PHP|function_exists('index36_func')} -->.
 *
 * Все функции обёрнуты в if (!function_exists()) для защиты от
 * повторного объявления и снабжены префиксом index36_ для защиты от
 * коллизий с функциями ядра, плагинов и модулей.
 *
 * Стиль кода: PHP 8.5. Строгая типизация возвращаемых значений,
 * параметризованные SQL-запросы, современные операторы (??, ?->),
 * подробные PHPDoc-блоки с описанием поведения и предупреждений.
 * ===================================================================== */


