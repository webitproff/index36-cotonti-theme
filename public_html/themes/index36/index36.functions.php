 *            . Cot::$cfg['defaulttheme'] . '/'
 *            . Cot::$cfg['defaulttheme'] . '.functions.php';
 *        Но это грязный приём — функция темы не должна работать
 *        вне контекста темы.
 *
 *     2. Продублировать логику в отдельной функции внутри
 *        functions.custom.php и вызывать её как из темы, так и из
 *        системных мест. Это чище, но требует дублирования кода.
