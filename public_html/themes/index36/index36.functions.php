 *  8. Обработка исключений.
 *     SQL-запросы и файловые операции оборачивать в try/catch
 *     с записью в error_log(), чтобы не обрушить страницу.
 *
 *  9. Минимум зависимостей.
 *     Чем меньше функция зависит от глобального состояния, тем
 *     проще её тестировать и переиспользовать. Передавать параметры
 *     явно, а не читать из глобальных переменных.
