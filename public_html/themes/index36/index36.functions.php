 * =====================================================================
 *
 *   Следующие действия приведут к ошибкам или нарушат работу движка:
 *
 *   - session_start() — сессия уже открыта движком;
 *   - setcookie(), setrawcookie() — заголовки уже частично отправлены;
 *   - header() — то же самое;
 *   - exit, die — прервут выполнение движка;
 *   - echo, print, printf, var_dump — сломают вывод;
 *   - обнуление $cfg, $usr, $sys — нарушит работу всех модулей;
 *   - вызов cot_redirect() при подключении — прервёт загрузку;
 *   - вызов cot_die_message(), cot_diefatal() без веской причины;
 *   - создание глобальных объектов при подключении файла;
