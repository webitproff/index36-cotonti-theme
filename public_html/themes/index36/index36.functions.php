/**
 * Возвращает значение revision из таблицы cot_updates.
 *
 * Что делает:
 *   Выполняет SELECT upd_value FROM cot_updates WHERE upd_param = 'revision'.
 *   Используется для отображения версии базы данных в футере или
 *   в административном разделе.
 *
 * Особенности поведения:
 *   - При успешном выполнении возвращает экранированное значение revision.
 *   - При отсутствии записи в таблице возвращает пустую строку.
 *   - При ошибке базы данных возвращает пустую строку и записывает
 *     подробность ошибки в error_log.
 *
 * Почему возвращается строка, а не null:
 *   Движок CoTemplate не проверяет результат на null. При возврате null
 *   в шаблоне появится пустая строка — это допустимо. Но если функция
 *   используется в PHP-коде темы без проверки, null может привести
 *   к неожиданному поведению. Возврат строки даёт единый контракт:
 *   функция всегда возвращает валидную строку, возможно пустую.
 *
 * Почему try/catch внутри функции:
 *   CoTemplate не оборачивает вызов в try/catch. Любое исключение PDO
 *   из этой функции всплывёт наружу и обрушит страницу. Локальная
 *   обработка исключения гарантирует, что страница останется в строю
 *   даже при сбое БД.
 *
 * Предупреждение о XSS:
 *   Значение revision приходит из БД и в теории может быть подменено
 *   злоумышленником с правами на запись в cot_updates. Поэтому результат
 *   экранируется через htmlspecialchars с флагами ENT_QUOTES
 *   (обрабатывает и одинарные, и двойные кавычки) и ENT_SUBSTITUTE
 *   (заменяет некорректные UTF-8-последовательности на символ замены
 *   вместо возврата пустой строки).
 *
 * Предупреждение о кэшировании:
 *   Если включён кэш шаблонов ($cfg['xtpl_cache']), содержимое
 *   скомпилированного шаблона не влияет на выполнение тега {PHP|...}.
 *   Тег вычисляется в момент рендеринга, а не при компиляции.
 *
 * @return string Экранированное значение revision или пустая строка.
 *
 * @example
 *   В шаблоне footer.tpl:
 *     <!-- IF {PHP|function_exists('index36_get_revision')} -->
 *         <li>{PHP.L.langSkStr_footer_db_version}: v.{PHP|index36_get_revision()}</li>
 *     <!-- ENDIF -->
 *
 *   В PHP-коде темы:
 *     $revision = index36_get_revision();
 *     if ($revision !== '') {
 *         Cot::$out['db_revision'] = $revision;
 *     }
 */
if (!function_exists('index36_get_revision')) {
    function index36_get_revision(): string
    {
        try {
            $sql = Cot::$db->query(
                'SELECT upd_value FROM ' . Cot::$db->updates . ' WHERE upd_param = ?',
                ['revision']
            );
            $value = $sql->fetchColumn();
        } catch (PDOException $e) {
            // Ошибку не пробрасываем наружу — иначе CoTemplate обрушит страницу.
            // Записываем в лог веб-сервера для диагностики администратором.
            error_log('index36_get_revision error: ' . $e->getMessage());

            return '';
        }

        // Пустая запись, отсутствие значения или не-строка — возвращаем пустую строку.
        if (!is_string($value) || $value === '') {
            return '';
        }

        // Экранируем для безопасной вставки в HTML.
        // ENT_QUOTES — обрабатывает ' и ".
        // ENT_SUBSTITUTE — заменяет некорректные UTF-8-байты на символ замены U+FFFD.
        return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }
}


/* =====================================================================
 * index36_php_version()
 * ===================================================================== */

/**
 * Возвращает версию PHP, на которой выполняется сайт.
 *
 * Что делает:
 *   Обёртка над встроенной функцией phpversion() с префиксом темы.
 *   Используется для отображения в футере, в отладочной панели или
 *   в административном разделе.
 *
 * Особенности поведения:
 *   - Всегда возвращает непустую строку, например «8.5.0» или «8.5.0-dev».
 *   - Значение всегда корректно с точки зрения кодировки — это гарантия
 *     стандарта PHP.
 *
 * Почему используется PHP_VERSION, а не phpversion():
 *   Константа PHP_VERSION содержит ту же информацию, но доступна без
 *   вызова функции. Это чуть быстрее и полностью эквивалентно по
 *   результату. Кроме того, использование константы явно сигнализирует,
 *   что значение не может измениться во время выполнения скрипта.
 *
 * Зачем htmlspecialchars на выходе:
 *   Формально в выводе PHP_VERSION не может быть HTML-опасных символов,
 *   но использование htmlspecialchars — единый защитный паттерн для всех
 *   функций, возвращающих данные в HTML-контекст. Это устраняет
 *   необходимость проверять каждую конкретную функцию на безопасность
 *   и защищает от будущих изменений в источнике данных.
 *
 * @return string Экранированная версия PHP, например «8.5.0».
 *
 * @example
 *   В шаблоне footer.tpl:
 *     <!-- IF {PHP|function_exists('index36_php_version')} -->
 *         <li>{PHP.L.langSkStr_footer_php_version}: {PHP|index36_php_version()}</li>
 *     <!-- ENDIF -->
 */
if (!function_exists('index36_php_version')) {
    function index36_php_version(): string
    {
        return htmlspecialchars(PHP_VERSION, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }
}


/* =====================================================================
 * index36_legacy_mode_status()
 * ===================================================================== */

/**
 * Возвращает локализованный статус legacy-режима Cotonti.
 *
 * Что делает:
 *   Проверяет значение Cot::$cfg['legacyMode'] и возвращает
 *   соответствующую языковую строку из языкового файла темы:
 *     - langSkStr_footer_legacy_mode_on  — если режим включён (true);
 *     - langSkStr_footer_legacy_mode_off — если режим выключен или не задан.
 *
 * Особенности поведения:
 *   - Возвращает готовую к вставке в HTML строку, уже локализованную.
 *   - Если соответствующей языковой строки нет в $L, возвращает пустую
 *     строку. Это безопасная деградация — никакого литерала вроде
 *     «langSkStr_footer_legacy_mode_on» в интерфейсе не появится.
 *   - Никогда не бросает исключений — функция не работает с БД
 *     и файловой системой.
 *
 * Почему Cot::$L, а не $L:
 *   Фасад Cot::$L — стабильный источник языковых строк в Cotonti V.1.
 *   Глобальная переменная $L может быть переопределена в других
 *   контекстах (например, в плагинах или при загрузке языкового файла
 *   темы). Использование Cot::$L гарантирует получение актуального
 *   значения из глобального реестра языка.
 *
 * Почему ?? '', а не прямой доступ к массиву:
 *   Если ключ отсутствует в массиве $L, прямой доступ вызовет
 *   PHP warning «Undefined array key» в PHP 8+. Оператор ??
 *   предотвращает warning и возвращает пустую строку — контракт
 *   функции остаётся единым: всегда возвращается строка.
 *
 * Как добавить языковые строки в тему:
 *   Создать или отредактировать файл
 *   themes/index36/index36.{lang_code}.lang.php и добавить в него:
 *     $L['langSkStr_footer_legacy_mode_on']  = '...';
 *     $L['langSkStr_footer_legacy_mode_off'] = '...';
 *   После этого функция вернёт соответствующее значение для каждой
 *   языковой версии темы.
 *
 * @return string Локализованный текст статуса или пустая строка.
 *
 * @example
 *   В шаблоне footer.tpl:
 *     <!-- IF {PHP|function_exists('index36_legacy_mode_status')} -->
 *         <li>{PHP.L.langSkStr_footer_legacy_mode}: {PHP|index36_legacy_mode_status()}</li>
 *     <!-- ENDIF -->
 *
 *   В PHP-коде темы:
 *     Cot::$out['legacyMode'] = index36_legacy_mode_status();
 */
if (!function_exists('index36_legacy_mode_status')) {
    function index36_legacy_mode_status(): string
    {
        // Определяем ключ языковой строки по состоянию флага legacyMode.
        // !empty() корректно обрабатывает true, 1, '1', 'on' и другие
        // значения, которые могут попасть в конфиг. Строгая проверка
        // === true здесь не используется намеренно: конфигурация
        // хранится как строки в БД и может быть представлена по-разному.
        $key = !empty(Cot::$cfg['legacyMode'])
            ? 'langSkStr_footer_legacy_mode_on'
            : 'langSkStr_footer_legacy_mode_off';

        // Возврат через ?? '' гарантирует строковый контракт:
        // если ключ отсутствует — вернётся пустая строка,
        // а не null и не warning.
        return Cot::$L[$key] ?? '';
    }
}